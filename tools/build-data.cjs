/*
 * Regenerate data/questions.js from data/questions.json.
 * questions.json is the source of truth (edit it), questions.js lets index.html work
 * even when opened directly from disk (file://), where fetch() of JSON is blocked.
 * Run:  node tools/build-data.cjs
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const json = fs.readFileSync(path.join(ROOT, 'data', 'questions.json'), 'utf8');
JSON.parse(json); // fail loudly on invalid JSON
const out = '/* Generated by tools/build-data.cjs from data/questions.json — do not edit by hand. */\n' +
  'window.TOEIC_BANK = ' + json.trim() + ';\n';
fs.writeFileSync(path.join(ROOT, 'data', 'questions.js'), out);
console.log('data/questions.js updated (' + JSON.parse(json).questions.length + ' questions)');
